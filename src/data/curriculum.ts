export function getTodayDayBn(): DayOfWeek {
  const parts = new Intl.DateTimeFormat('en-US', {
    timeZone: 'Asia/Dhaka',
    weekday: 'short',
  }).format(new Date());

  const shortMap: Record<string, DayOfWeek> = {
    Sun: 'রবিবার',
    Mon: 'সোমবার',
    Tue: 'মঙ্গলবার',
    Wed: 'বুধবার',
    Thu: 'বৃহস্পতিবার',
    Fri: 'শুক্রবার',
    Sat: 'শনিবার',
  };
  return shortMap[parts] ?? 'শনিবার';
}

interface SubjectSeed {
  code: string;
  nameBn: string;
  nameEn: string;
  department: DepartmentId | 'common';
  offerings: SubjectOffering[];
  theoryPeriods: number;
  practicalPeriods: number;
  credits: number;
  chapters: { titleBn: string; topicsBn: string[]; minutes?: number }[];
  materials?: StudyMaterial[];
  formulas?: string[];
  practicalGuides?: PracticalGuide[];
  diagramTypes?: CircuitDiagramType[];
}

function buildSubject(seed: SubjectSeed): Subject {
  const primarySemester = seed.offerings[0]?.semester ?? 1;
  const chapters = seed.chapters.map((ch, idx) => ({
    id: `ch-${seed.code}-${idx + 1}`,
    number: idx + 1,
    titleBn: ch.titleBn,
    topicsBn: ch.topicsBn,
    estimatedMinutes: ch.minutes ?? 55,
  }));

  const defaultMaterials: StudyMaterial[] =
    seed.materials && seed.materials.length > 0
      ? seed.materials
      : [
          {
            id: `mat-${seed.code}-syllabus`,
            titleBn: `BTEB প্রবিধান-২০২২ সিলেবাস ও পরীক্ষার নির্দেশিকা (${seed.code})`,
            type: seed.formulas && seed.formulas.length > 0 ? 'formula-sheet' : 'syllabus',
            summaryBn: `${seed.nameEn} (${seed.code}) — তত্ত্বীয় ${seed.theoryPeriods} পিরিয়ড, ব্যবহারিক ${seed.practicalPeriods} পিরিয়ড, মোট ${seed.credits} ক্রেডিট।`,
            keyPointsBn: [
              `বিষয়ের নাম: ${seed.nameBn} (${seed.nameEn})`,
              `তত্ত্বীয়/ব্যবহারিক বণ্টন: T-${seed.theoryPeriods}, P-${seed.practicalPeriods}, C-${seed.credits}`,
              `প্রধান টপিকসমূহ: ${seed.chapters.map((c) => c.titleBn).join(', ')}`,
            ],
            formulas: seed.formulas,
            externalUrl: 'https://bteb.gov.bd/',
          },
        ];

  return {
    id: `sub-${seed.code}`,
    code: seed.code,
    nameBn: seed.nameBn,
    nameEn: seed.nameEn,
    department: seed.department,
    semester: primarySemester,
    offerings: seed.offerings,
    credits: seed.credits,
    theoryPeriods: seed.theoryPeriods,
    practicalPeriods: seed.practicalPeriods,
    probidhan: '2022',
    chapters,
    materials: defaultMaterials,
    practicalGuides: seed.practicalGuides,
    diagramTypes: seed.diagramTypes,
  };
}

