export const SUBJECTS_CATALOG: Subject[] = CURRICULUM_SEEDS.map(buildSubject);

export function getSubjectsForUser(department: DepartmentId, semester: SemesterNumber): Subject[] {
  return SUBJECTS_CATALOG.filter((s) => {
    if (s.offerings && s.offerings.length > 0) {
      return s.offerings.some(
        (offering) => offering.department === department && offering.semester === semester
      );
    }
    return s.semester === semester && (s.department === department || s.department === 'common');
  });
}
